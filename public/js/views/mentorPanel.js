// Slide-over mentor chat available from every page.
import { h, icon, md } from '../ui.js';
import { getState, addMentorMessage, clearMentor } from '../store.js';
import { askMentor, detectBackend, SUGGESTIONS } from '../mentor.js';

let panel, list, input, sendBtn, modeBadge, getCtx = () => ({});
let busy = false, isOpen = false, lastFocus = null;

export function initMentor({ getContext }) {
  getCtx = getContext;
  modeBadge = h('span.mode-badge.sim', 'Simulated');
  list = h('div.chat-log', { role: 'log', 'aria-live': 'polite', 'aria-label': 'Conversation with the mentor' });
  input = h('textarea.chat-input', { rows: 1, placeholder: 'Ask about a concept, your progress, or what to study next…', 'aria-label': 'Message the mentor' });
  sendBtn = h('button.btn.btn-primary.send', { type: 'submit', 'aria-label': 'Send message' }, icon('send', 18));
  input.addEventListener('keydown', (e) => { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); form.requestSubmit(); } });
  input.addEventListener('input', () => { input.style.height = 'auto'; input.style.height = `${Math.min(input.scrollHeight, 140)}px`; });
  const form = h('form.chat-form', { onsubmit: (e) => { e.preventDefault(); send(input.value); } }, input, sendBtn);
  panel = h('aside.mentor-panel', { 'aria-label': 'AI mentor', 'aria-hidden': 'true', inert: true },
    h('header.mentor-head',
      h('div.mentor-avatar', icon('compass', 22)),
      h('div', h('h2', 'Mentor'), h('p.small', modeBadge, h('span.muted', ' Uses your saved progress'))),
      h('button.icon-btn', { onclick: () => { clearMentor(); renderLog(); }, title: 'Clear conversation', 'aria-label': 'Clear conversation' }, icon('reset', 18)),
      h('button.icon-btn', { onclick: closeMentor, title: 'Close', 'aria-label': 'Close mentor' }, icon('x', 20))),
    list,
    h('div.suggestions', { 'aria-label': 'Suggested questions' }, SUGGESTIONS.map((t) => h('button.chip', { type: 'button', onclick: () => send(t) }, t))),
    form,
    h('p.chat-note.small.muted#mentor-note', 'Simulated mentor: replies are generated by rules from the course content and your progress — not by a live AI model.'));
  const scrim = h('div.mentor-scrim', { onclick: closeMentor });
  document.body.append(scrim, panel);
  document.addEventListener('keydown', (e) => { if (e.key === 'Escape' && isOpen) closeMentor(); });
  panel.addEventListener('click', (e) => { const a = e.target.closest('a[href^="#/"]'); if (a && window.matchMedia('(max-width: 900px)').matches) closeMentor(); });
  detectBackend().then((b) => {
    if (b) {
      modeBadge.textContent = 'Live AI'; modeBadge.className = 'mode-badge live';
      document.getElementById('mentor-note').textContent = `Live mentor via your server (${b.provider}). Your progress summary is sent with each message.`;
    }
  });
  renderLog();
}

function bubble(m) {
  return h(`div.msg.msg-${m.role}`,
    m.role === 'assistant' ? h('div.msg-avatar', { 'aria-hidden': 'true' }, icon('compass', 16)) : null,
    h('div.msg-body',
      h('div.prose', { html: md(m.text) }),
      m.role === 'assistant' && m.simulated ? h('span.msg-tag', 'Simulated reply') : m.role === 'assistant' && m.simulated === false ? h('span.msg-tag.live', 'AI-generated') : null));
}

function renderLog() {
  const msgs = getState().mentor.messages;
  const greeting = { role: 'assistant', simulated: true, text: `Hi ${getState().profile.name}! I’m your learning mentor. I can explain GenAI concepts, give hints without spoiling answers, review your test results, and suggest what to study next based on your saved progress.\n\nTry one of the suggestions below, or ask me anything.` };
  list.replaceChildren(...(msgs.length ? msgs : [greeting]).map(bubble));
  list.scrollTop = list.scrollHeight;
}

async function send(text) {
  text = String(text || '').trim();
  if (!text || busy) return;
  busy = true; sendBtn.disabled = true;
  input.value = ''; input.style.height = 'auto';
  const history = getState().mentor.messages;
  addMentorMessage({ role: 'user', text }, { asked: true });
  renderLog();
  const typing = h('div.msg.msg-assistant.typing', h('div.msg-avatar', icon('compass', 16)), h('div.msg-body', h('span.dots', { 'aria-label': 'Mentor is typing' }, h('i'), h('i'), h('i'))));
  list.append(typing); list.scrollTop = list.scrollHeight;
  try {
    const reply = await askMentor(getState(), text, history, getCtx());
    addMentorMessage({ role: 'assistant', text: reply.text, simulated: reply.simulated });
  } catch (e) {
    addMentorMessage({ role: 'assistant', text: `Sorry — something went wrong (${e.message}).`, simulated: true });
  }
  busy = false; sendBtn.disabled = false;
  renderLog();
  input.focus();
}

export function openMentor(prefill) {
  if (!panel) return;
  lastFocus = document.activeElement;
  isOpen = true;
  document.body.classList.add('mentor-open');
  panel.removeAttribute('inert'); panel.setAttribute('aria-hidden', 'false');
  renderLog();
  setTimeout(() => input.focus(), 50);
  if (prefill) send(prefill);
}

export function closeMentor() {
  isOpen = false;
  document.body.classList.remove('mentor-open');
  panel.setAttribute('inert', ''); panel.setAttribute('aria-hidden', 'true');
  lastFocus?.focus?.();
}
