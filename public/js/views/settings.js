import { h, icon, toast, modal } from '../ui.js';
import * as store from '../store.js';
import { CONFIG } from '../data/config.js';
import { detectBackend } from '../mentor.js';

export function renderSettings(_, { refresh }) {
  const s = store.getState();
  const nameIn = h('input#set-name', { type: 'text', value: s.profile.name, maxlength: 40 });
  const thIn = h('input#set-th', { type: 'number', min: CONFIG.minPassThreshold, max: CONFIG.maxPassThreshold, step: 5, value: s.settings.passThreshold });
  const bossIn = h('input#set-boss', { type: 'checkbox', checked: s.settings.requireBoss });
  const fileIn = h('input', { type: 'file', accept: 'application/json,.json', class: 'sr-only', id: 'import-file' });
  const backendInfo = h('p.small', 'Checking…');
  detectBackend().then((b) => { backendInfo.replaceChildren(b ? h('span.ok', icon('check', 14), ` Live AI backend connected (${b.provider}). Replies are generated by a real model via your server.`) : h('span', icon('info', 14), ' No AI backend configured — the mentor is running in simulated mode. See README → "Connecting a real AI mentor".')); });

  fileIn.addEventListener('change', async () => {
    const f = fileIn.files[0];
    if (!f) return;
    try { store.importState(JSON.parse(await f.text())); toast('Progress imported', { iconName: 'check' }); refresh(); }
    catch (e) { toast(e.message || 'Could not import that file', { kind: 'warn' }); }
  });

  return h('section.page.settings', { 'data-title': 'Settings' },
    h('header.page-head', h('p.kicker', 'Settings'), h('h1', 'Settings and data')),
    h('div.settings-grid',
      h('section.card', h('h2', 'Profile'),
        h('div.field', h('label', { for: 'set-name' }, 'Display name'), nameIn),
        h('button.btn.btn-primary', { onclick: () => { store.setName(nameIn.value.trim() || 'Learner'); toast('Name saved', { iconName: 'check' }); } }, 'Save name')),
      h('section.card', h('h2', 'Progression rules'),
        h('div.field', h('label', { for: 'set-th' }, 'Test pass mark (%)'), thIn,
          h('p.small.muted', `Default ${CONFIG.defaultPassThreshold}%. Applies to future attempts; past attempts keep the pass mark they were graded with.`)),
        h('div.field.check', bossIn, h('label', { for: 'set-boss' }, 'Require boss challenges to unlock the next level')),
        h('button.btn.btn-primary', { onclick: () => { store.setThreshold(thIn.value); store.setRequireBoss(bossIn.checked); toast(`Saved: pass mark ${store.getState().settings.passThreshold}%`, { iconName: 'check' }); refresh(); } }, 'Save rules')),
      h('section.card', h('h2', 'Mentor connection'), backendInfo,
        h('p.small.muted', 'API keys are never stored in the browser. A real provider is configured on the server with an environment variable.')),
      h('section.card', h('h2', 'Your data'),
        h('p.small.muted', 'Progress is saved in this browser (localStorage). Export it from the Progress report; import it here.'),
        h('div.hero-actions',
          h('label.btn.btn-ghost', { for: 'import-file', tabindex: 0, role: 'button', onkeydown: (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); fileIn.click(); } } }, icon('upload', 16), 'Import progress JSON'), fileIn),
        h('div.danger',
          h('h3', 'Reset'),
          s.isSample ? h('p.small', h('strong', 'You are currently viewing sample progress. '), 'Start fresh to begin your own journey from Level 1.') : null,
          h('div.hero-actions',
            h('button.btn.btn-danger', { onclick: () => modal({ title: 'Start fresh?', body: 'This permanently deletes all saved progress in this browser — lessons, test attempts, XP, badges and mentor chat — and starts you at Level 1. Export first if you want a backup. This cannot be undone.', actions: [{ label: 'Delete progress and start fresh', kind: 'danger', onClick: () => { store.resetProgress('fresh'); toast('Fresh start — welcome to Spark Plains!', { iconName: 'spark' }); location.hash = '#/dashboard'; } }, { label: 'Cancel', autofocus: true }] }) }, icon('reset', 16), 'Start fresh'),
            h('button.btn.btn-ghost', { onclick: () => modal({ title: 'Load sample progress?', body: 'This replaces your current progress with the sample learner data. Your current progress will be lost unless you export it first.', actions: [{ label: 'Load sample data', onClick: () => { store.resetProgress('sample'); toast('Sample progress loaded'); location.hash = '#/dashboard'; } }, { label: 'Cancel', autofocus: true }] }) }, 'Load sample data'))))));
}
